import Byte
import ISO_32000_Flate
import RFC_1950
import Testing

@testable import ISO_32000

@Suite
struct `ISO_32000.Image Tests` {

    static let rgba: [Byte] = [
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0xF4, 0x22, 0x7F,
        0x8A, 0x00, 0x00, 0x00, 0x11, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0xF8, 0xCF, 0xC0, 0xD0,
        0xC0, 0xF0, 0x9F, 0xE1, 0x3F, 0x00, 0x0E, 0x7D, 0x03, 0x7E, 0xEA, 0xF6, 0x93, 0xC0, 0x00, 0x00,
        0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    ].map(Byte.init(bitPattern:))

    static let grayscaleAlpha: [Byte] = [
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x01, 0x08, 0x04, 0x00, 0x00, 0x00, 0x5E, 0x2B, 0xB7,
        0x01, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0xE0, 0x12, 0x91, 0xD3,
        0x00, 0x00, 0x00, 0xCD, 0x00, 0x65, 0x6A, 0x99, 0x84, 0x42, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
        0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    ].map(Byte.init(bitPattern:))

    @Test
    func `an RGBA PNG keeps its alpha channel as a soft mask`() throws {
        let image = try ISO_32000.Image(png: Self.rgba)
        let softMask = try #require(image.softMask)

        #expect(try RFC_1950.decompress(image.data) == [255, 0, 0, 0, 255, 0].map(Byte.init(bitPattern:)))
        #expect(try RFC_1950.decompress(softMask) == [128, 255].map(Byte.init(bitPattern:)))
    }

    @Test
    func `a grayscale PNG with alpha keeps its alpha channel as a soft mask`() throws {
        let image = try ISO_32000.Image(png: Self.grayscaleAlpha)
        let softMask = try #require(image.softMask)

        #expect(image.colorSpace == .deviceGray)
        #expect(try RFC_1950.decompress(image.data) == [10, 30].map(Byte.init(bitPattern:)))
        #expect(try RFC_1950.decompress(softMask) == [20, 40].map(Byte.init(bitPattern:)))
    }

    @Test
    func `an image with a soft mask is written with an SMask image`() throws {
        let image = try ISO_32000.Image(png: Self.rgba)
        let page = ISO_32000.Page(
            mediaBox: .letter,
            content: ISO_32000.ContentStream { _ in },
            resources: ISO_32000.Resources(fonts: [:], xObjects: [image.resourceName: image])
        )
        var writer = ISO_32000.Writer()
        let str = try String(decoding: writer.write(ISO_32000.Document(pages: [page])), as: UTF8.self)

        #expect(str.contains("/SMask "))
        #expect(str.ranges(of: "/Subtype /Image").count == 2)
        #expect(str.contains("/ColorSpace /DeviceGray"))
    }

    @Test
    func `a JPEG image has no soft mask`() throws {
        let jpeg: [Byte] = [
            0xFF, 0xD8, 0xFF, 0xC0, 0x00, 0x0B, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00,
        ].map(Byte.init(bitPattern:))
        let image = try ISO_32000.Image(jpeg: jpeg)
        #expect(image.softMask == nil)
    }
}
